    private static async Task<IReadOnlyList<ContractOperation>> ReadOperationsAsync()
    {
        var path = Path.Combine(FindRepoRoot(), ClientContract.Replace('/', Path.DirectorySeparatorChar));
        using var document = JsonDocument.Parse(await File.ReadAllTextAsync(path, TestContext.Current.CancellationToken));
        var operations = new List<ContractOperation>();
        foreach (var pathItem in document.RootElement.GetProperty("paths").EnumerateObject())
        {
            foreach (var member in pathItem.Value.EnumerateObject())
            {
                if (HttpVerbs.Contains(member.Name, StringComparer.Ordinal))
                {
                    operations.Add(new ContractOperation(
                        member.Value.GetProperty("operationId").GetString()!,
                        member.Name,
                        pathItem.Name));
                }
            }
        }

        return operations;
    }

    private static async Task<IReadOnlyList<string>> ReadGeneratedOperationsAsync(string language)
    {
        var root = FindRepoRoot();
        var (directory, filePattern, excludedFragment) = language switch
        {
            "TypeScript" => ("languages/typescript/src", "index.ts", "/models/"),
            "Python" => ("languages/python/src/yogabase_client", "*_request_builder.py", "/models/"),
            "Java" => ("languages/java/src/main/java/io/yogabase/client", "*RequestBuilder.java", "/delivery/"),
            "Dart" => ("languages/dart/lib/src", "*_request_builder.dart", "/delivery/"),
            _ => throw new ArgumentOutOfRangeException(nameof(language), language, "Not a Kiota language."),
        };

        var found = new HashSet<string>(StringComparer.Ordinal);
        foreach (var file in Directory.EnumerateFiles(
            Path.Combine(root, directory.Replace('/', Path.DirectorySeparatorChar)),
            filePattern,
            SearchOption.AllDirectories))
        {
            var normalized = file.Replace(Path.DirectorySeparatorChar, '/');
            if (normalized.Contains(excludedFragment, StringComparison.Ordinal))
            {
                continue;
            }

            var text = await File.ReadAllTextAsync(file, TestContext.Current.CancellationToken);
            foreach (var operation in ScanGeneratedBuilder(language, text))
            {
                found.Add(operation);
            }
        }

        return [.. found];
    }

    // The (verb, path) pairs one generated request builder declares: its URI template and each HTTP method it has.
    private static IEnumerable<string> ScanGeneratedBuilder(string language, string text)
    {
        var (template, verbs) = language switch
        {
            "TypeScript" => (
                Regex.Match(text, "UriTemplate = \"(?<t>[^\"]+)\";"),
                Regex.Matches(text, @"^    (?<v>get|post|put|delete|patch): \{\r?\n\s+uriTemplate: ", RegexOptions.Multiline)),
            "Python" => (
                Regex.Match(text, "super\\(\\)\\.__init__\\(request_adapter, \"(?<t>[^\"]+)\", path_parameters\\)"),
                Regex.Matches(text, @"def to_(?<v>get|post|put|delete|patch)_request_information\(")),
            "Java" => (
                Regex.Match(text, "super\\(requestAdapter, \"(?<t>[^\"]+)\", pathParameters\\)"),
                Regex.Matches(text, @"new RequestInformation\(HttpMethod\.(?<v>GET|POST|PUT|DELETE|PATCH),")),
            "Dart" => (
                Regex.Match(text, "super\\(requestAdapter, \"(?<t>[^\"]+)\", pathParameters\\)"),
                Regex.Matches(text, @"httpMethod : HttpMethod\.(?<v>get|post|put|delete|patch),")),
            _ => throw new ArgumentOutOfRangeException(nameof(language), language, "Not a Kiota language."),
        };

        if (!template.Success)
        {
            yield break;
        }

        var path = template.Groups["t"].Value.Replace("{+baseurl}", string.Empty, StringComparison.Ordinal);
        var query = path.IndexOf("{?", StringComparison.Ordinal);
        if (query >= 0)
        {
            path = path[..query];
        }

        foreach (Match verb in verbs)
        {
            yield return verb.Groups["v"].Value.ToUpperInvariant() + " " + path;
        }
    }

