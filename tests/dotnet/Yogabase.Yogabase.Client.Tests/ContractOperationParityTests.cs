    [Fact]
    public async Task EveryOperationOfTheContractIsAccountedForAndNoEntryOutlivesItsOperation()
    {
        var operations = (await ReadOperationsAsync()).Select(static operation => operation.OperationId).ToArray();

        Assert.Equal(operations.Length, operations.Distinct(StringComparer.Ordinal).Count());
        var accounted = DotNetCalls.Keys
            .Concat(DotNetExclusions.Keys)
            .Append(ConfigurationOperation)
            .ToArray();

        var missing = operations.Except(accounted, StringComparer.Ordinal).Order(StringComparer.Ordinal).ToArray();
        var stale = accounted.Except(operations, StringComparer.Ordinal).Order(StringComparer.Ordinal).ToArray();
        Assert.True(
            missing.Length == 0,
            $"The mirrored contract declares operations this repository does not account for: {string.Join(", ", missing)}. "
            + "Give each a .NET surface (a row in DotNetCalls), authored clients where the language has them, and regenerate the "
            + "Kiota clients; or exclude it with a reason.");
        Assert.True(
            stale.Length == 0,
            $"These entries name operations the mirrored contract no longer declares: {string.Join(", ", stale)}.");
        Assert.Empty(DotNetCalls.Keys.Intersect(DotNetExclusions.Keys, StringComparer.Ordinal));

        // An authored client may only wrap an operation the contract has.
        Assert.Empty(Authored.Keys.Except(operations, StringComparer.Ordinal));
    }

