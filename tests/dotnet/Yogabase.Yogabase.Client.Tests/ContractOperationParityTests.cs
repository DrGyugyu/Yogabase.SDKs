        var generated = (await ReadGeneratedOperationsAsync(language)).Order(StringComparer.Ordinal).ToArray();

        var missing = expected.Except(generated, StringComparer.Ordinal).ToArray();
        var extra = generated.Except(expected, StringComparer.Ordinal).ToArray();
        Assert.True(
            missing.Length == 0 && extra.Length == 0,
            $"The generated {language} client does not match the mirrored contract. Missing: [{string.Join(", ", missing)}]. "
            + $"Not in the contract (stale): [{string.Join(", ", extra)}]. Run scripts/regenerate-clients.sh.");
    }

    [Theory]
    [MemberData(nameof(GeneratedLanguages))]
    public async Task TheAuthoredJobsAndScheduleClientsOfTheLanguageDeclareEveryOperationTheyWrap(string language)
    {
        var root = FindRepoRoot();
        var missing = new List<string>();
        foreach (var (operationId, tokens) in Authored)
        {
            foreach (var token in tokens.Where(token => token.Language == language))
            {
                var path = Path.Combine(root, token.File.Replace('/', Path.DirectorySeparatorChar));
                if (!File.Exists(path))
                {
                    missing.Add($"{operationId}: {token.File} does not exist");
                    continue;
                }

                var text = await File.ReadAllTextAsync(path, TestContext.Current.CancellationToken);
                if (!text.Contains(token.Token, StringComparison.Ordinal))
                {
                    missing.Add($"{operationId}: {token.File} no longer declares '{token.Token}'");
                }
            }
        }

        Assert.True(missing.Count == 0, string.Join(Environment.NewLine, missing));
        // Every wrapped operation has an authored declaration in every Kiota language, none is left out.
        Assert.All(Authored.Values, tokens => Assert.Contains(tokens, token => token.Language == language));
    }

    [Fact]
    public async Task TheKiotaLocksOfEveryGeneratedTreeTieItToTheContractItWasGeneratedFrom()
    {
        var root = FindRepoRoot();
