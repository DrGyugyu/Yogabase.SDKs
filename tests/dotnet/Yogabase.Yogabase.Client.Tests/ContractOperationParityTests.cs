                    Path.Combine(root, lockFile.Replace('/', Path.DirectorySeparatorChar)),
                    TestContext.Current.CancellationToken));
                Assert.Equal(
                    recorded.GetProperty("kiotaDescriptionHash").GetString(),
                    document.RootElement.GetProperty("descriptionHash").GetString(),
                    StringComparer.OrdinalIgnoreCase);
            }
        }
    }

