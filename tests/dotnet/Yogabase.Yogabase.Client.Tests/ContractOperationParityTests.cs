    [Fact]
    public async Task TheJobsLimitsStatusesAndCodesAreTheOnesTheAuthoredClientsCarry()
    {
        using var document = await ReadContractAsync();
        var root = document.RootElement;
        var jobs = root.GetProperty("x-yogabase-jobs");
        var limits = jobs.GetProperty("limits");

        Assert.Equal(YogabaseJobsLimits.MaximumPayloadBytes, limits.GetProperty("maximumPayloadBytes").GetInt32());
        Assert.Equal(YogabaseJobsLimits.MaximumAttempts, limits.GetProperty("maximumAttempts").GetInt32());
        Assert.Equal(YogabaseJobsLimits.MaximumJobTypeLength, limits.GetProperty("maximumJobTypeLength").GetInt32());
        Assert.Equal(YogabaseJobsLimits.MaximumIdempotencyKeyLength, limits.GetProperty("maximumIdempotencyKeyLength").GetInt32());
        Assert.Equal(YogabaseJobsLimits.MaximumResultBytes, limits.GetProperty("maximumResultBytes").GetInt32());
        Assert.Equal(5, limits.GetProperty("defaultMaxAttempts").GetInt32());
        Assert.Equal(8_391_225, limits.GetProperty("maximumRequestBodyBytes").GetInt32());

        var refusal = jobs.GetProperty("refusal");
        Assert.Equal(413, refusal.GetProperty("status").GetInt32());
        Assert.Equal(YogabaseJobErrors.PayloadTooLarge, refusal.GetProperty("code").GetString());
        Assert.Equal(["limitBytes", "maxBodyBytes"], refusal.GetProperty("members").EnumerateArray().Select(static value => value.GetString()).ToArray());

        // Every code a Jobs route refuses with is a constant the client names, and every gateway constant is declared.
        var declared = new HashSet<string>(StringComparer.Ordinal);
        foreach (var operation in jobs.GetProperty("refusalCodes").EnumerateObject())
        {
            foreach (var code in operation.Value.EnumerateObject())
            {
                declared.Add(code.Name);
            }
        }

        var constants = typeof(YogabaseJobErrors).GetFields()
            .Where(static field => field.IsLiteral)
            .Select(static field => (string)field.GetRawConstantValue()!)
            .ToHashSet(StringComparer.Ordinal);
        // The two the client names itself, for an answer that is not what the route declares.
        constants.ExceptWith([YogabaseJobErrors.ResponseInvalid, YogabaseJobErrors.ResultDigestMismatch]);
        Assert.Equal(declared.Order(StringComparer.Ordinal), constants.Order(StringComparer.Ordinal));

        var statuses = root.GetProperty("components").GetProperty("schemas").GetProperty("JobStatus").GetProperty("enum")
            .EnumerateArray().Select(static value => value.GetString()!).ToArray();
        Assert.Equal(statuses, Enum.GetNames(typeof(YogabaseJobStatus)));
    }

