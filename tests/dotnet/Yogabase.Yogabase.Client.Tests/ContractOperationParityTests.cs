/// <summary>
/// Holds every shipped language to the mirrored client OpenAPI document, operation by operation, so a contract
/// change without an SDK change fails here instead of in a consumer. The document is the product's: when a
/// re-mirror adds, drops or moves an operation this test names it, and the change is not finished until each
/// language has a surface for it or an exclusion that says why it has none.
/// </summary>
/// <remarks>
/// <para>
/// What counts as a surface differs by language, and so does how it is proved. The .NET client has no
/// generated code: a recording handler exercises its public API and the first request each call makes must be
/// the contract's verb and path (so the proof is behavioural, and a route that is spelled right but never
/// called, or called with another verb, fails). TypeScript, Python, Java and Dart are generated by Kiota
/// from the same document: their trees must hold a request builder for exactly the contract's (verb, path)
/// pairs, no more and no fewer (read from the generated sources as text, which is the only check a language
/// this repository cannot run, Dart, can have here), and each language's authored Jobs and schedule clients,
/// which sit beside the generated builders because a Kiota builder cannot read a response header, must still
/// declare every operation they wrap.
/// </para>
/// <para>
/// An exclusion is an operation a language has no surface for on purpose. There is exactly one family, the
/// provider return routes in the .NET client (a browser calls them, never an application), and the test pins
/// the list so that a new exclusion cannot be added without editing this file's reason for it.
/// </para>
/// </remarks>
public sealed class ContractOperationParityTests
