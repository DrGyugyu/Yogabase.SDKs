    [Fact]
    public async Task TheDotNetClientSendsEveryOperationItDoesNotExcludeToTheContractsVerbAndPath()
    {
        var operations = (await ReadOperationsAsync()).ToDictionary(static operation => operation.OperationId, StringComparer.Ordinal);
        var recorded = new List<(string Method, string Path)>();
        var handler = new RecordingHandler(recorded);
        var failures = new List<string>();

        foreach (var (operationId, calls) in DotNetCalls)
        {
            var operation = operations[operationId];
            foreach (var call in calls)
            {
                // A fresh client for every call: a sign-out clears the session, and the calls after it would
                // otherwise be refused for want of a token before they reached the transport.
                await using var client = await ClientAsync(handler);
                recorded.Clear();
                await InvokeIgnoringTheOutcomeAsync(() => call.Invoke(client));
                Check(failures, operation, call.Symbol, recorded.Count <= call.Prepared ? null : recorded[call.Prepared]);
            }
        }

        Assert.True(failures.Count == 0, string.Join(Environment.NewLine, failures));
    }

    [Fact]
    public async Task TheDotNetClientFetchesTheBootstrapDocumentFromTheContractsRoute()
    {
        var operation = (await ReadOperationsAsync()).Single(static operation => operation.OperationId == ConfigurationOperation);
        var recorded = new List<(string Method, string Path)>();

        await InvokeIgnoringTheOutcomeAsync(() => YogabaseClient.CreateAsync(
            new Uri("http://localhost/"),
            "sy_pub_example_project",
            new YogabaseClientOptions { AllowInsecureLoopback = true, TransportHandler = new RecordingHandler(recorded) }));

        var failures = new List<string>();
        Check(failures, operation, "YogabaseClient.CreateAsync", recorded.Count == 0 ? null : recorded[0]);
        Assert.True(failures.Count == 0, string.Join(Environment.NewLine, failures));
    }

