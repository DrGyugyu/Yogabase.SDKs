    private static void Check(List<string> failures, ContractOperation operation, string symbol, (string Method, string Path)? sent)
    {
        if (sent is not { } request)
        {
            failures.Add($"{operation.OperationId}: {symbol} sent no request.");
            return;
        }

        var pattern = "^" + Regex.Replace(Regex.Escape(operation.Path), @"\\\{[^}/]+\}", "[^/]+") + "$";
        if (!string.Equals(request.Method, operation.Verb, StringComparison.OrdinalIgnoreCase)
            || !Regex.IsMatch(request.Path, pattern, RegexOptions.CultureInvariant))
        {
            failures.Add(
                $"{operation.OperationId}: {symbol} sent {request.Method} {request.Path}, the contract says {operation.Verb.ToUpperInvariant()} {operation.Path}.");
        }
    }

